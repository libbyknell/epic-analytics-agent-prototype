#!/usr/bin/env python3
"""404-check.py — load every beat's starter page headless (file://) and fail on any failed
request (404s, broken relative CSS/font/icon paths, etc) or dead local link. Generated by kit-init.sh.

Usage: python3 _kit/404-check.py [path/to/manifest.tsv]
Default manifest: <project-dir>/_kit/manifest.tsv (relative to this script's own location).
Exit code: 0 if every beat loaded clean, 1 if any beat had a failed/4xx/5xx request.
"""
import sys
import re
import pathlib
import urllib.parse
from playwright.sync_api import sync_playwright

HERE = pathlib.Path(__file__).resolve().parent
PROJECT_DIR = HERE.parent
MANIFEST = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "manifest.tsv"

if not MANIFEST.exists():
    print(f"ERROR: manifest not found at {MANIFEST}", file=sys.stderr)
    sys.exit(2)

rows = []
with open(MANIFEST) as f:
    for line in f:
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 5:
            continue
        beat_id, screen_type, folder, gate_surface, page_rel = parts[:5]
        rows.append((beat_id, screen_type, page_rel))

if not rows:
    print("ERROR: no beats found in manifest", file=sys.stderr)
    sys.exit(2)

overall_fail = False

with sync_playwright() as pw:
    browser = pw.chromium.launch(headless=True)
    for beat_id, screen_type, page_rel in rows:
        page_path = (PROJECT_DIR / page_rel).resolve()
        failures = []
        page = browser.new_page()

        def on_response(resp):
            if resp.status >= 400:
                failures.append(f"{resp.status} {resp.url}")

        def on_requestfailed(req):
            failures.append(f"FAILED {req.url} ({req.failure})")

        page.on("response", on_response)
        page.on("requestfailed", on_requestfailed)

        if not page_path.exists():
            print(f"[404-check] {beat_id} ({screen_type}): MISSING FILE {page_path}")
            overall_fail = True
            page.close()
            continue

        # static check: local href/src targets that never issue a request (e.g. <a href>)
        html = page_path.read_text(errors="ignore")
        # commented-out slots (e.g. the org-logo brand slot) are not live requests
        html = re.sub(r"<!--.*?-->", "", html, flags=re.S)
        for m in re.finditer(r"""(?:href|src)\s*=\s*(["'])([^"']+)(["'])""", html):
            u = m.group(2)
            # src="img/ic-' + name + '.png" inside a JS string: the quotes don't pair, so it is not a literal URL
            if m.group(1) != m.group(3):
                continue
            if re.match(r"(#|[a-zA-Z][a-zA-Z0-9+.-]*:|//|\{|\$)", u):
                continue
            target = urllib.parse.unquote(u.split("#")[0].split("?")[0])
            if target and not (page_path.parent / target).exists():
                failures.append(f"DEAD-LINK {u} (no such file next to {page_path.name})")

        page.goto(f"file://{page_path}", wait_until="load")
        page.wait_for_timeout(300)  # let fonts/late CSS settle
        page.close()

        if failures:
            overall_fail = True
            print(f"[404-check] {beat_id} ({screen_type}): FAIL ({len(failures)} bad request(s))")
            for f in failures:
                print(f"    {f}")
        else:
            print(f"[404-check] {beat_id} ({screen_type}): clean, 0 failed requests")
    browser.close()

sys.exit(1 if overall_fail else 0)
